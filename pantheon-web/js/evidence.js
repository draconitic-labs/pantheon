export function rec(key) {
  const d = REG[key];
  if (!d) {
    console.warn(`evidence: unregistered key '${key}'`);
    return {
      cls: IL, source: 'unregistered evidence key', citation: String(key),
      frame: '—', note: 'no record for this key', fetched: null,
    };
  }
  return {
    cls: d[0], source: d[1], citation: d[2], frame: d[3], note: d[4],
    fetched: d[5] ? RETRIEVED : null,
  };
}
